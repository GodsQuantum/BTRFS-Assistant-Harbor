#include "util/RemoteBackupPlan.h"
#include <QDebug>
#define REQUIRE(condition) do { if (!(condition)) qFatal("Check failed: %s", #condition); } while (false)
#include <QStringList>
#include <QUuid>
int main() {
  using namespace HarborRemote;
  const QString id = profileId("root", "/mnt/backup");
  REQUIRE(!QUuid(id).isNull());
  REQUIRE(id == "3554efe8-75e3-59bd-97a3-0526b0fd90e2");
  REQUIRE(id == profileId("root", "/mnt/backup"));
  REQUIRE(id != profileId("home", "/mnt/backup"));
  REQUIRE(archiveName("root", 123) == "snap-root-123");
  REQUIRE(archiveName("root/unsafe", 123).isEmpty());
  const QStringList send = sendArguments("root", 123, "/mnt/backup", false);
  REQUIRE(send.contains("selected-snapper"));
  REQUIRE(send.contains("--experimental"));
  REQUIRE(send.contains("--snapper-number"));
  REQUIRE(send.contains("123"));
  REQUIRE(!send.contains("--allow-local"));
  REQUIRE(sendArguments("root", 123, "/non-existing/../../etc", false).isEmpty());
  REQUIRE(sendArguments("root", 0, "/mnt/backup", false).isEmpty());
  REQUIRE(sendArguments("root", 123, "relative", false).isEmpty());
  REQUIRE(sendArguments("root", 123, "/mnt/backup", true).contains("--allow-local"));
  const QStringList schedule = scheduleArguments("root", "/mnt/backup", false);
  REQUIRE(schedule.contains("schedule-run"));
  REQUIRE(schedule.contains("--name-prefix"));
  REQUIRE(schedule.contains(profileId("root", "/mnt/backup")));
  const QStringList restore = previewRestoreArguments("/mnt/backup", "snap-root-123", "/mnt/staging");
  REQUIRE(restore.contains("--dry-run"));
  REQUIRE(restore.contains("raw:///mnt/backup"));
  REQUIRE(previewRestoreArguments("/mnt/backup", "../invalid", "/mnt/staging").isEmpty());
  REQUIRE(previewRestoreArguments("/mnt/backup", "snap-root-123", "/").isEmpty());
  const QStringList pending = transfersArguments("/mnt/backup");
  REQUIRE(pending.contains("list"));
  REQUIRE(pending.contains("checkpoint-v2"));
  REQUIRE(transfersArguments("relative").isEmpty());
  const QString uuid = QStringLiteral("a5d970db-9664-4be8-a0fb-bb1e93c60ec3");
  const QStringList resume = resumeArguments("/mnt/backup", "snap-root-123", uuid, false);
  REQUIRE(resume.contains("resume"));
  REQUIRE(resume.contains("--transfer-id"));
  REQUIRE(resume.contains(uuid));
  REQUIRE(resume.contains("--experimental"));
  REQUIRE(!resume.contains("--allow-local"));
  REQUIRE(resumeArguments("/mnt/backup", "snap-root-123", uuid, true).contains("--allow-local"));
  REQUIRE(resumeArguments("/mnt/backup", "../invalid", uuid, false).isEmpty());
  REQUIRE(resumeArguments("/mnt/backup", "snap-root-123", "bad-uuid", false).isEmpty());
  const QString casPath("/mnt/dedicated-cas");
  const QString sourcePath("/.snapshots/123/snapshot");
  const QString parentPath("/.snapshots/122/snapshot");
  REQUIRE(casInitArguments(casPath, false).contains("init"));
  REQUIRE(casInitArguments("/", false).isEmpty());
  REQUIRE(casListArguments(casPath).contains("list"));
  REQUIRE(casPrunePreviewArguments(casPath, "snap-root-123").contains("--name"));
  REQUIRE(!casPrunePreviewArguments(casPath).contains("--name"));
  REQUIRE(casPrunePreviewArguments(casPath, "../oops").isEmpty());
  REQUIRE(casPrunePreviewArguments("relative", "snap-root-123").isEmpty());
  REQUIRE(casPruneConfirmArguments(casPath, "snap-root-123", QString(64, 'a')).contains("--confirm-plan"));
  REQUIRE(casPruneConfirmArguments(casPath, "snap-root-123", "stale").isEmpty());

  REQUIRE(casSendArguments(casPath, "root", 123, sourcePath, false, QString(), 0, false).contains("send"));
  const auto casIncremental=casSendArguments(casPath, "root", 123, sourcePath, true, parentPath, 122, false);
  REQUIRE(casIncremental.contains("--parent"));
  REQUIRE(casIncremental.contains("--parent-archive"));
  REQUIRE(casIncremental.contains("snap-root-122"));
  REQUIRE(casIncremental.contains("--experimental"));
  REQUIRE(casSendArguments(casPath, "root", 123, sourcePath, true, parentPath, 0, false).isEmpty());
  REQUIRE(casSendArguments(casPath, "root", 123, "../bad", false, QString(), 0, false).isEmpty());
  REQUIRE(casVerifyArguments(casPath, "snap-root-123").contains("verify-stream"));
  REQUIRE(casPreviewArguments(casPath, "snap-root-123", "/mnt/restore").contains("--preview"));
  REQUIRE(casConfirmArguments(casPath, "snap-root-123", "/mnt/restore").contains("--confirm"));
  REQUIRE(casConfirmArguments(casPath, "../bad", "/mnt/restore").isEmpty());
  REQUIRE(trustedBackendExecutable("/usr/bin/python3"));
  REQUIRE(!trustedBackendExecutable("/tmp/harbor-masquerade"));
  REQUIRE(!trustedBackendExecutable("/home/arezki/bin/btrfs-backup-ng"));
  REQUIRE(!trustedBackendExecutable("/usr/bin/../../tmp/harbor-masquerade"));
  const auto casId = profileIdForEngine("root", "/mnt/backup", true);
  REQUIRE(!casId.isEmpty());
  REQUIRE(casId != profileIdForEngine("root", "/mnt/backup", false));
  const auto casSchedule = scheduleInstallerArguments("root", "/mnt/backup", "daily", false, true);
  REQUIRE(casSchedule.contains("--engine"));
  REQUIRE(casSchedule.contains("cas"));
  REQUIRE(!casSchedule.contains("--allow-local"));
  REQUIRE(scheduleInstallerArguments("root", "/mnt/backup", "hourly", true, true).contains("--allow-local"));
  REQUIRE(!scheduleInstallerArguments("root", "/mnt/backup", "daily", false, false).contains("--engine"));
  REQUIRE(scheduleInstallerArguments("root", "/mnt/backup", "everyminute", false, true).isEmpty());
  const QStringList verify = verifyArguments("/mnt/backup", "snap-root-123");
  REQUIRE(verify.contains("--json"));
  REQUIRE(verify.contains("--snapshot"));
  return 0;
}
